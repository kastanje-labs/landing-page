type Props = { size?: number; className?: string };
export function PixelIcon({
  name,
  size = 18,
  className,
}: { name: string } & Props) {
  return (
    <svg
      width={size}
      height={size}
      className={className}
      viewBox="0 0 16 16"
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {shapes[name] ? (
        <path fillRule="evenodd" d={shapes[name]} />
      ) : (
        (icons[name] ?? icons.overview).flatMap((row, y) =>
          [...row].flatMap((p, x) =>
            p === "1" ? (
              <rect x={x} y={y} width="1" height="1" key={`${x}-${y}`} />
            ) : (
              []
            ),
          ),
        )
      )}
    </svg>
  );
}
const icon = (name: string) => (props: Props) => (
  <PixelIcon name={name} {...props} />
);
